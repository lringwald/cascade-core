require(cli)
require(data.table)
options(cli.progress_show_after = 0)

#' High-Resolution Spatial Downscaling of Land Use
#'
#' @description
#' The main entry point for downscaling aggregate thematic targets (e.g., land use areas) to a high-resolution grid
#' using an iterative cross-entropy multinomial logit solver.
#'
#' @param targets A `data.table` of aggregate thematic targets to hit.
#' @param start_areas A `data.table` of initial pixel-level areas.
#' @param times A vector of timesteps to process.
#' @param xmat A `data.table` of spatially explicit explanatory variables.
#' @param betas A `data.table` of coefficients matching `xmat` to transition classes.
#' @param areas_update_fun A function to update areas dynamically across timesteps.
#' @param xmat_coltypes Optional specification of variable column types.
#' @param xmat_proj Optional `data.table` for dynamic/projected explanatory variables over time.
#' @param xmat_dyn_fun A function to dynamically update `xmat` variables.
#' @param priors A `data.table` of exogenous spatial priors.
#' @param restrictions A `data.table` of hard transition restrictions (0 or 1).
#' @param options A list of control options generated by `downscale_control()`.
#'
#' @return A `data.table` of downscaled high-resolution simulated areas across time.
#' @export
downscale <- function(targets,
                      start_areas,
                      times = NULL,
                      xmat = NULL,
                      betas = NULL,
                      areas_update_fun = areas_sum_to,
                      xmat_coltypes = NULL,
                      xmat_proj = NULL,
                      xmat_dyn_fun = xmat_sum_to,
                      priors = NULL,
                      restrictions = NULL,
                      options = downscale_control()) {
  message("⚙️  Starting preprocessing...")
  from_class = value = proj = ks = dyn = to_class = NULL
  
  # 1. Ensure Base data.table Format
  targets      <- as.data.table(targets)
  start_areas  <- as.data.table(start_areas)
  if (!is.null(xmat)) xmat <- as.data.table(xmat)
  if (!is.null(betas)) betas <- as.data.table(betas)
  if (!is.null(priors)) priors <- as.data.table(priors)
  if (!is.null(restrictions)) restrictions <- as.data.table(restrictions)
  if (!is.null(xmat_proj)) xmat_proj <- as.data.table(xmat_proj)
  
  # 2. Extract Dictionary & Apply Globally (Using aux_func.R)
  global_levels <- extract_global_levels(targets, start_areas, priors, restrictions, xmat, xmat_proj, times)
  
  # 3. SET IT ONCE IN THE OPTIONS
  # Save the old options so we can restore them later
  old_opts <- options(downscalr.global_levels = global_levels)
  
  # on.exit guarantees the options are wiped when the function finishes or errors out,
  # preventing memory leaks or interference with other models.
  on.exit(options(old_opts), add = TRUE)
  
  targets      <- standardize_factors(targets)
  start_areas  <- standardize_factors(start_areas)
  xmat         <- standardize_factors(xmat)
  betas        <- standardize_factors(betas)
  priors       <- standardize_factors(priors)
  restrictions <- standardize_factors(restrictions)
  xmat_proj    <- standardize_factors(xmat_proj)
  
  # 3. Completion Steps
  targets     = complete_targets(targets)
  start_areas = complete_areas(start_areas)
  target_area_check(targets, start_areas)
  
  if (is.null(xmat)) {
    xmat = data.table(ns = unique(start_areas$ns), ks = factor(PLCHOLD_K, levels = global_levels$ks), value = 0)
  }
  xmat = complete_xmat(xmat, start_areas)
  
  if (is.null(betas)) {
    betas = data.table(to_class = factor(PLCHOLD_LU, levels = global_levels$to_class), ks = unique(xmat$ks), value = 0)
  }
  betas = complete_betas(betas)
  
  xmat_coltypes = complete_xmat_coltypes(xmat_coltypes, xmat)
  
  if (!is.null(priors)) priors = complete_priors(priors, xmat, targets)
  if (!is.null(restrictions)) restrictions = complete_restrictions(restrictions, xmat, targets)
  if (!is.null(xmat_proj)) xmat_proj = complete_xmat_proj(xmat_proj)
  
  # 4. Final Validation
  err_check_inputs(
    targets, start_areas, xmat, betas, areas_update_fun, xmat_coltypes, 
    xmat_proj, xmat_dyn_fun, priors, restrictions, options$err.txt
  )
  
  # Column types
  proj_colnames = if (any(xmat_coltypes$value == "projected")) xmat_coltypes[value == "projected"]$ks else NULL
  dyn_colnames  = if (any(xmat_coltypes$value == "dynamic")) xmat_coltypes[value == "dynamic"]$ks else NULL
  
  message("✅ Preprocessing complete. Starting iterations over times...")
  
  # Retrieve the strictly sorted times from our dictionary, excluding the placeholder
  run_times = setdiff(global_levels$times, PLCHOLD_T) 
  
  curr_areas = start_areas
  curr_xmat  = xmat
  
  # Pre-allocate lists for high-speed aggregation
  out_res_list <- list()
  out_solver   <- list()
  out_diag_list <- list()
  
  cli_h2("Downscaling optimization")
  pb <- cli_progress_bar(
    total = length(run_times),
    format = " ⚙️ {pb_bar} {pb_percent} | Year: {curr_time} | ETA: {pb_eta}",
    format_done = " ✅ Optimization complete in {pb_elapsed}."
  )
  
  # 5. Iteration Loop
  for (curr_time in run_times) {
    missing_luc = NULL
    
    valid_targets_lu <- unique(targets[times == curr_time, from_class])
    
    if (!all(unique(curr_areas$from_class) %in% valid_targets_lu)) {
      missing_luc <- curr_areas[!from_class %in% valid_targets_lu, .(ns, from_class, to_class = from_class, value)]
    }
    
    curr_options = options
    curr_options$err.txt = paste0(curr_time, " ", curr_options$err.txt)

    if (options$solve_fun == "solve_biascorr") {
      res = solve_biascorr_unified(
        type = "lu",
        targets = targets, 
        areas = curr_areas, 
        xmat = curr_xmat, 
        betas = betas, 
        priors = priors, 
        restrictions = restrictions,
        timestep = curr_time, 
        options = curr_options
      )
    } else if (options$solve_fun == "solve_notarget") {
      res = solve_notarget_mnl(
        targets = targets[times == curr_time], 
        areas = curr_areas, 
        xmat = curr_xmat, 
        betas = betas, 
        restrictions = if (!is.null(restrictions)) restrictions[times == curr_time] else NULL, 
        options = curr_options
      )
    }
    
    if (!is.null(missing_luc)) res$out_res = rbindlist(list(res$out_res, missing_luc), use.names = TRUE, fill = TRUE)
    
    # Update current areas
    curr_areas = areas_update_fun(res$out_res, curr_areas, priors, xmat_proj)
    # Update projected xmats
    if (!is.null(xmat_proj) && !is.null(proj_colnames)) {
      tmp_proj = xmat_proj[times == curr_time]
      setnames(tmp_proj, "value", "proj")
      curr_xmat[tmp_proj, on = .(ns, ks), value := fifelse(!is.na(proj), proj, value)]
      setnames(tmp_proj, "proj", "value")
    }
    
    # Update dynamic xmats
    if (!is.null(dyn_colnames)) {
      tmp_dyn = xmat_dyn_fun(res, curr_areas, priors, xmat, xmat_proj)
      setnames(tmp_dyn, "value", "dyn")
      curr_xmat[tmp_dyn[ks %in% dyn_colnames], on = .(ns, ks), value := fifelse(!is.na(dyn), dyn, value)]
    }
    
    # Store results in the pre-allocated lists
    res_agg = cbind(times = factor(curr_time, levels = global_levels$times, ordered = TRUE), res$out_res)
    out_res_list[[curr_time]] <- res_agg
    out_solver[[curr_time]]   <- res$solver_runs
    out_diag_list[[curr_time]] <- res$out_diag
    
    cli_progress_update(id = pb, set = which(run_times == curr_time))
  }
  cli_progress_done(id = pb)
  
  # 6. Post-processing
  out_res <- rbindlist(out_res_list, use.names = TRUE, fill = TRUE)
  
  # Remove placeholders
  out_res <- out_res[to_class != PLCHOLD_LU]
  if (any(out_res$from_class == PLCHOLD_LU)) out_res[, from_class := NULL]
  if (any(out_res$times == PLCHOLD_T)) out_res[, times := NULL]
  
  return(list(
    out_res = out_res,
    out_diagnostic = rbindlist(out_diag_list),
    out_solver = out_solver
  ))
}
