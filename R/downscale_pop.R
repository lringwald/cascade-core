require(progress)
require(cli)
options(cli.progress_show_after = 0)
#' High-Resolution Spatial Downscaling of Population
#'
#' @description
#' The main entry point for downscaling aggregate population target counts to a high-resolution grid
#' using an iterative poisson/IPF solver.
#'
#' @param targets A `data.table` of aggregate population targets to hit.
#' @param start_grid A `data.table` of initial pixel-level population counts or capacities.
#' @param times A vector of timesteps to process.
#' @param xmat A `data.table` of spatially explicit explanatory variables.
#' @param betas A `data.table` of coefficients matching `xmat` to population groups.
#' @param areas_update_fun A function to update population baselines dynamically across timesteps.
#' @param xmat_coltypes Optional specification of variable column types.
#' @param xmat_proj Optional `data.table` for dynamic/projected explanatory variables over time.
#' @param xmat_dyn_fun A function to dynamically update `xmat` variables.
#' @param priors A `data.table` of exogenous spatial priors.
#' @param restrictions A `data.table` of hard transition restrictions (0 or 1).
#' @param options A list of control options generated by `downscale_control_pop()`.
#'
#' @return A `data.table` of downscaled high-resolution simulated population counts across time.
#' @export
downscale_pop <- function(targets,
                          start_grid = NULL,
                          times = NULL,
                          xmat = NULL,
                          betas = NULL,
                          areas_update_fun = areas_sum_to,
                          xmat_coltypes = NULL,
                          xmat_proj = NULL,
                          xmat_dyn_fun = xmat_sum_to,
                          priors = NULL,
                          restrictions = NULL,
                          options = downscale_control_pop()) {
  # ----------------------------------------------------------------------------
  # Setup: convert to data.table, source auxiliary code
  # ----------------------------------------------------------------------------
  message("⚙️  Starting preprocessing...")
  # Ensure data.tables
  targets      <- if (!is.data.table(targets)) as.data.table(targets) else targets
  start_grid   <- if (!is.null(start_grid) && !is.data.table(start_grid)) as.data.table(start_grid) else start_grid
  xmat         <- if (!is.null(xmat) && !is.data.table(xmat)) as.data.table(xmat) else xmat
  betas        <- if (!is.null(betas) && !is.data.table(betas)) as.data.table(betas) else betas
  priors       <- if (!is.null(priors) && !is.data.table(priors)) as.data.table(priors) else priors
  restrictions <- if (!is.null(restrictions) && !is.data.table(restrictions)) as.data.table(restrictions) else restrictions
  xmat_proj    <- if (!is.null(xmat_proj) && !is.data.table(xmat_proj)) as.data.table(xmat_proj) else xmat_proj

  # ----------------------------------------------------------------------------
  # Input completion / checks
  # ----------------------------------------------------------------------------
  targets   <- complete_targets_pop(targets)

  # if (is.null(start_grid)) {
  #   # We may allow implicit start_grid based on priors
  #   start_grid <- compute_default_start_pop(targets, priors)
  # }
  start_grid <- complete_start_grid_pop(start_grid,targets)

  if (is.null(xmat)) {
    xmat <- data.table(ns = unique(start_grid$ns),
                       ks = PLCHOLD_K,
                       value = 0)
  }

  xmat <- complete_xmat(xmat, start_grid)

  if (is.null(betas)) {
    betas <- data.table(pop_type = PLCHOLD_POPT,
                        ks = unique(xmat$ks),
                        value = 0)
  }

  betas <- complete_betas_pop(betas)

  xmat_coltypes <- complete_xmat_coltypes(xmat_coltypes, xmat)
  if (!is.null(xmat_proj)) xmat_proj <- complete_xmat_proj(xmat_proj)
  if (!is.null(priors)) priors <- complete_priors_pop(priors, xmat, targets)
  if (!is.null(restrictions)) restrictions <- complete_restrictions_pop(restrictions, xmat, targets)

  err_check_inputs_pop(
    targets,
    xmat,
    betas,
    xmat_coltypes,
    xmat_proj,
    xmat_dyn_fun,
    priors,
    restrictions,
    options$err.txt
  )

  # ----------------------------------------------------------------------------
  # Identify which ks are “projected” or “dynamic”
  # ----------------------------------------------------------------------------
  proj_colnames <- NULL
  dyn_colnames  <- NULL
  if (any(xmat_coltypes$value == "projected")) {
    proj_colnames <- xmat_coltypes[value == "projected"]$ks
  }
  if (any(xmat_coltypes$value == "dynamic")) {
    dyn_colnames <- xmat_coltypes[value == "dynamic"]$ks
  }

  # ----------------------------------------------------------------------------
  # Iteration over times
  # ----------------------------------------------------------------------------
  message("✅ Preprocessing done. Starting downscaling over time steps...")
  if (is.null(times)) times <- sort(unique(targets$times))
  curr_xmat   <- xmat
  out_solver  <- list()
  curr_time <- times[1]
  # Progress bar
  cli_h2("LSU Downscaling optimization")
  pb <- cli_progress_bar(
    total = length(times),
    format = " {pb_spin} {pb_bar} {pb_percent} | ETA: {pb_eta} | Step {pb_current}/{pb_total} | {pb_elapsed} | Time: {curr_time}",
    format_done = "{pb_spin} LSU Optimization complete in {pb_elapsed}."
  )

  for (curr_time in times) {

    # Solve (currently only bias‑correcting Poisson or similar method)
    if (options$solve_fun == "solve_biascorr") {
      curr_opts <- options
      curr_opts$err.txt <- paste0(curr_time, " ", curr_opts$err.txt)
      res <- solve_biascorr_unified(
                                  type = "pop",
                                  targets = targets,
                                  grid = start_grid,
                                  xmat = curr_xmat,
                                  betas = betas,
                                  priors = priors,
                                  restrictions = restrictions,
                                  timestep = curr_time,
                                  options = curr_opts
                                )
    } else {
      stop("Other solve_fun methods not yet implemented in downscale_pop")
    }

    # Update projected xmat (if any)
    if (!is.null(xmat_proj) && length(proj_colnames) > 0) {
      tmp_proj <- xmat_proj[times == curr_time]
      setnames(tmp_proj, "value", "proj")
      curr_xmat[tmp_proj, on = .(ns, ks), value := fifelse(!is.na(proj), proj, value)]
    }
    # Update dynamic xmat (if any)
    if (length(dyn_colnames) > 0) {
      tmp_dyn <- xmat_dyn_fun(res, curr_grid, priors, xmat, xmat_proj)
      setnames(tmp_dyn, "value", "dyn")
      curr_xmat[tmp_dyn[ks %in% dyn_colnames], on = .(ns, ks),
                value := fifelse(!is.na(dyn), dyn, value)]
    }

    # Append results
    res_dt <- cbind(times = curr_time, res$out_res)
    if (!exists("out_res")) {
      out_res <- res_dt
    } else {
      out_res <- rbind(out_res, res_dt, fill = TRUE)
    }
    out_solver[[as.character(curr_time)]] <- res$out_solver
    cli_progress_update(id = pb, set = which(times == curr_time))
  }
  cli_progress_done(id = pb)
  # End time loop

  # Drop placeholder levels / dummy pop_types
  out_res <- out_res[pop_type != PLCHOLD_POPT]
  if (any(out_res$times == PLCHOLD_T)) out_res[, times := NULL]

  return(list(
    out_res   = out_res,
    out_solver = out_solver,
    ds.inputs = list(
      targets     = targets,
      start_grid  = start_grid,
      xmat         = xmat,
      betas        = betas,
      xmat_coltypes    = xmat_coltypes,
      xmat_proj     = xmat_proj,
      xmat_dyn_fun  = xmat_dyn_fun,
      priors        = priors,
      restrictions  = restrictions,
      options       = options
    )
  ))
}
